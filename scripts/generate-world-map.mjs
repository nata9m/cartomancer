#!/usr/bin/env node
/**
 * Generates apps/web/src/lib/world-map-data.ts, the geometry behind map mode (#52).
 *
 * The output is committed, so the app has no runtime dependency on any of this:
 * one SVG path per country, already projected, and nothing to fetch or compute in
 * the browser. Re-run it only to change the map (the projection, the level of
 * detail, the source data):
 *
 *   mkdir /tmp/geo && cd /tmp/geo && npm init -y
 *   npm i world-atlas@2.0.2 topojson-client topojson-simplify d3-geo i18n-iso-countries
 *   GEO_MODULES=/tmp/geo node scripts/generate-world-map.mjs
 *
 * Those packages are deliberately not dependencies of this repository.
 *
 * Source: Natural Earth (public domain), 1:50m countries, via the world-atlas
 * package. Matched to our countries by ISO 3166-1 numeric code, which is what
 * world-atlas uses as a feature id, via i18n-iso-countries. The 50m set has all
 * but one of the 195 (Tuvalu), which is taken from the 1:10m set.
 *
 * Countries are simplified together as a topology (shared borders stay shared,
 * so there are no slivers between neighbours), then projected with Natural Earth.
 * Anything on the map that is not one of the 195 — Greenland, Taiwan, Kosovo,
 * Western Sahara — is drawn as inert land so the map has no holes, but cannot be
 * the answer to anything.
 */
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const geoRequire = createRequire(path.join(process.env.GEO_MODULES ?? root, 'noop.js'));
const topo = geoRequire('topojson-client');
const { presimplify, simplify, quantile } = geoRequire('topojson-simplify');
const { geoNaturalEarth1, geoPath } = geoRequire('d3-geo');
const iso = geoRequire('i18n-iso-countries');

const WIDTH = 1000;
const HEIGHT = 520;
/** Fraction of the finest points to drop; 0.2 is ~230 kB of path data and still reads well at 4x zoom. */
const SIMPLIFY = 0.2;
/** Below this projected area (px² of the 1000-wide map) a country is too small to hit, and gets a marker. */
const TINY_AREA = 8;
const ANTARCTICA = '010';

const { COUNTRIES } = await import(path.join(root, 'packages/shared/dist/index.js'));

const load = (file) =>
  JSON.parse(fs.readFileSync(geoRequire.resolve(`world-atlas/${file}`), 'utf8'));

let t50 = load('countries-50m.json');
t50 = simplify(presimplify(t50), quantile(presimplify(t50), SIMPLIFY));
const features50 = topo.feature(t50, t50.objects.countries).features;
const t10 = load('countries-10m.json');
const features10 = topo.feature(t10, t10.objects.countries).features;

const projection = geoNaturalEarth1().fitExtent(
  [
    [4, 4],
    [WIDTH - 4, HEIGHT - 4],
  ],
  { type: 'Sphere' },
);
const toPath = geoPath(projection).digits(1);
const numeric = (feature) => String(feature.id ?? '').padStart(3, '0');

const used = new Set();
const countries = [];
for (const country of COUNTRIES) {
  const code = iso.alpha2ToNumeric(country.isoCode.toUpperCase());
  if (!code) throw new Error(`no numeric code for ${country.isoCode}`);
  const feature =
    features50.find((candidate) => numeric(candidate) === code && candidate.geometry) ??
    features10.find((candidate) => numeric(candidate) === code && candidate.geometry);
  if (!feature) throw new Error(`no geometry for ${country.name}`);
  used.add(code);

  const d = toPath(feature);
  const [cx, cy] = toPath.centroid(feature);
  const area = toPath.area(feature);
  countries.push({
    iso: country.isoCode.toLowerCase(),
    name: country.name,
    d,
    cx: Math.round(cx * 10) / 10,
    cy: Math.round(cy * 10) / 10,
    tiny: area < TINY_AREA,
  });
}

const otherLand = features50
  .filter(
    (feature) => feature.geometry && !used.has(numeric(feature)) && numeric(feature) !== ANTARCTICA,
  )
  .map((feature) => toPath(feature))
  .join('');

const body = `/**
 * GENERATED by scripts/generate-world-map.mjs — do not edit by hand (#52).
 * Natural Earth (public domain), 1:50m, via world-atlas 2.0.2; Natural Earth
 * projection, ${WIDTH}x${HEIGHT}.
 */
import type { WorldMapData } from './world-map';

export const WORLD_MAP: WorldMapData = {
  width: ${WIDTH},
  height: ${HEIGHT},
  otherLand: ${JSON.stringify(otherLand)},
  countries: ${JSON.stringify(countries)},
};
`;
fs.writeFileSync(path.join(root, 'apps/web/src/lib/world-map-data.ts'), body);
console.log(
  `${countries.length} countries, ${countries.filter((c) => c.tiny).length} tiny, ${(body.length / 1024).toFixed(0)} kB`,
);
